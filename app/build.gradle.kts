    from(configurations.getByName("debugRuntimeClasspath").filter {
        it.extension == "jar" && (it.name.startsWith("okhttp-") || it.name.startsWith("okio-") || it.name.startsWith("kotlin-stdlib"))
    })
    into(rootProject.file(".cache/verification/updater-libs"))
}
