tasks.withType<Test>().configureEach {
    dependsOn("copyRobolectricSdk")
    systemProperty("robolectric.offline", "true")
    systemProperty("robolectric.dependency.dir", rootProject.file(".cache/verification/robolectric-sdk").absolutePath)
}

